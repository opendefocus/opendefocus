//! Built-in sample scenes shown in the UI, with their embedded image and depth bytes.

/// Depth lens settings a sample needs because the defaults do not suit its depth values.
pub struct SampleLens {
    /// Depth interpretation: 0 for real depth values, 1 for one divided by Z.
    pub math: i32,
    /// Depth value that is in focus.
    pub focal_plane: f32,
    /// Blur radius in pixels per unit of relative depth error.
    pub size: f32,
    /// Largest blur radius in pixels.
    pub max_size: f32,
}

/// A built-in sample scene: its embedded image and optional depth, and how the depth is interpreted.
pub struct Sample {
    /// Name shown in the sample menu.
    pub name: &'static str,
    /// Encoded image bytes, decoded when the sample is loaded.
    pub image: &'static [u8],
    /// Encoded depth bytes, or `None` when the sample has no depth map.
    pub depth: Option<&'static [u8]>,
    /// Whether the depth map stores direct CoC values rather than depth.
    pub direct_coc: bool,
    /// The source `CoC` uses the opposite polarity from the renderer (negative foreground).
    pub invert_direct_coc: bool,
    /// Lens settings of the depth, or `None` to keep the evaluation defaults.
    pub lens: Option<SampleLens>,
}

